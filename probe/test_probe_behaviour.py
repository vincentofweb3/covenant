"""Phase 0: characterise two behaviours the first probe run exposed.

Neither question is about contract correctness -- both are about what direct
mode can and cannot prove. Getting either wrong would corrupt Phase 2's test
plan, which is why they are pinned here first.
"""

import pytest

from ._common import CALLEE, CALLER, COVENANT, PEER_HEX, SDK_VERSION, _reset_contract_registry


def test_autogenerated_dynarray_length_on_a_fresh_deploy(direct_deploy):
	"""A `DynArray` that was never appended to: does len() read back 0?"""
	callee = direct_deploy(CALLEE, "salt-1", sdk_version=SDK_VERSION)

	print(f"\n  fresh DynArray: len={len(callee.calls)} call_count()={callee.call_count()}")
	assert callee.call_count() == 0


def test_cross_contract_view_is_undeliverable_in_direct_mode(direct_deploy, direct_vm):
	"""Direct mode logs and drops cross-contract calls.

	knot's MEMORY.md claims this; this confirms it for our std lib and pins a
	reference so Phase 2 does not try to prove it here.
	"""
	direct_deploy(CALLEE, "salt-1", sdk_version=SDK_VERSION)
	_reset_contract_registry()

	caller = direct_deploy(CALLER, PEER_HEX, COVENANT, sdk_version=SDK_VERSION)

	try:
		result = caller.read_peer("act-x")
	except Exception as exc:  # noqa: BLE001 - the message is the observation
		result = f"raised: {exc}"

	print(f"\n  cross-contract view returned: {result!r}")
	print(f"  traces: {direct_vm._traces}")

	# The contract null-checks before coercing, so the failure is loud instead
	# of returning the string "None".
	assert "cross-contract read returned nothing" in str(result)


def test_cross_contract_write_is_undeliverable_in_direct_mode(direct_deploy, direct_vm):
	"""Same question for a write. Direct mode cannot prove the callee ran."""
	direct_deploy(CALLEE, "salt-1", sdk_version=SDK_VERSION)
	_reset_contract_registry()

	caller = direct_deploy(CALLER, PEER_HEX, COVENANT, sdk_version=SDK_VERSION)
	caller.ping_peer("act-y", "hello")

	print(f"\n  traces after emit: {direct_vm._traces}")
	assert any("PostMessage" in trace for trace in direct_vm._traces)


def test_deploying_a_second_contract_disturbs_the_first_stored_deploy(direct_deploy):
	"""Why `callee.call_count()` read 1 in the first probe run.

	Sequence: deploy callee, read its DynArray length, deploy caller, read the
	same length again. If it changes, storage slots are shared or clobbered
	across contract instances in one VMContext -- so no direct-mode test may
	assert on the *other* contract's storage afterwards.
	"""
	callee = direct_deploy(CALLEE, "salt-1", sdk_version=SDK_VERSION)
	before = callee.call_count()

	_reset_contract_registry()
	direct_deploy(CALLER, PEER_HEX, COVENANT, sdk_version=SDK_VERSION)
	after = callee.call_count()

	print(f"\n  callee.call_count() before second deploy={before} after={after}")

	# Asserted so that if a future gltest fixes this, the suite tells us and we
	# can relax the direct-mode one-contract rule.
	assert before == 0
	assert after != before